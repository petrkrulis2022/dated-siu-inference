/**
 * v3a's seeded print path (docs/experiment-3a-design.md, "Prints"). The print moves once per window along a path generated before the run from a committed seed that
 * stays hidden until the run ends (its sha256 is recorded at freeze), so agents cannot see ahead and a run's length in minutes never changes what they see.
 *
 *  - Zero drift: each window's move is a factor (1 + e), e symmetric about zero with standard deviation `volPpm` (parts per million of the print per window). The
 *    expected next print is today's, so neither currency is favoured by the direction of prices.
 *  - Integers throughout (invariant 4): e is an Irwin-Hall draw, twelve uniform integers summed and centred, which has mean zero and standard deviation one in its own
 *    units, scaled by `volPpm`. It is bounded at six standard deviations, so even the 5% setting can never take the print to zero.
 *  - The Commodity and Frontier prints move by the same factor: the fixed-basket print is what moves. Each task class's price also follows its own small independent
 *    walk (`classNoisePpm`), so relative prices between task types drift a little.
 *  - A burn-in of `burnIn` prints before window 1, generated by the same process and labelled simulated, is the history agents see from the first round; its last point
 *    is the opening print (window 0, genesis).
 */
import { D, type DecimalValue } from "@touchstone/sdk";
import { createHash } from "node:crypto";
import { SeedStream } from "../tasks/seeds.js";
import type { TaskId } from "../tasks/instances.js";
import type { NanoUsdPerSiu } from "./units.js";

const PPM = 1_000_000n;

export interface PricePathSpec {
  seed: string;
  /** daily volatility: the standard deviation of one window's move, parts per million */
  volPpm: bigint;
  /** each task class's own independent daily noise, parts per million */
  classNoisePpm: bigint;
  /** prints of simulated history before window 1; the last is the opening print */
  burnIn: number;
  windows: number;
  /** where the burn-in starts */
  start: { commodity: NanoUsdPerSiu; frontier: NanoUsdPerSiu };
  classes: readonly TaskId[];
}

export interface PathPoint {
  /** window index: 1..windows for the run, 0 for the opening print, negative for the earlier burn-in */
  window: number;
  simulated: boolean;
  rates: { commodity: NanoUsdPerSiu; frontier: NanoUsdPerSiu };
  /** each class's price factor, parts per million of its base price (1,000,000 = unchanged) */
  classPpm: Partial<Record<TaskId, bigint>>;
}

/** sha256 of a price-path seed: what the config records at freeze while the seed itself stays hidden */
export const pricePathSeedHash = (seed: string): string =>
  createHash("sha256").update(`v3a-price-path:${seed}`).digest("hex");

/** one zero-mean draw with standard deviation `sdPpm`, parts per million: Irwin-Hall (12 uniforms), integers only */
export function shockPpm(s: SeedStream, sdPpm: bigint): bigint {
  let sum = 0n;
  for (let i = 0; i < 12; i++) sum += BigInt(s.next(1_000_000));
  // twelve uniforms on [0, 1e6) sum to mean 12 * 499,999.5; centring on 5,999,994 leaves a mean of zero in the half-unit, and one unit of sd is 1e6
  const z = 2n * sum - 11_999_988n; // twice the centred sum, so the half-unit is exact
  return (z * sdPpm) / (2n * PPM);
}

const step = (v: bigint, ePpm: bigint): bigint => (v * (PPM + ePpm)) / PPM;

export function pricePath(spec: PricePathSpec): PathPoint[] {
  if (spec.burnIn < 1) throw new Error("price path: the burn-in needs at least one print (the opening print)");
  const s = new SeedStream(spec.seed, "v3a-price-path");
  const out: PathPoint[] = [];
  let commodity = spec.start.commodity;
  let frontier = spec.start.frontier;
  const classPpm = Object.fromEntries(spec.classes.map((c) => [c, PPM])) as Partial<Record<TaskId, bigint>>;
  const first = -(spec.burnIn - 1);
  for (let k = first; k <= spec.windows; k++) {
    if (k > first) {
      const e = shockPpm(s, spec.volPpm);
      commodity = step(commodity, e);
      frontier = step(frontier, e);
      for (const c of spec.classes) classPpm[c] = step(classPpm[c] as bigint, shockPpm(s, spec.classNoisePpm));
    }
    out.push({ window: k, simulated: k <= 0, rates: { commodity, frontier }, classPpm: { ...classPpm } });
  }
  return out;
}

/** a published print's `dated_siu` decimal string, for the volatility measure */
export interface DatedPrint {
  date: string;
  datedSiu: string;
}

export interface Volatility {
  /** consecutive calendar-day pairs of prints */
  pairs: number;
  /** sample standard deviation of the daily moves, parts per million, rounded half up */
  sdPpm: bigint;
  maxMove: { date: string; ppm: bigint };
  first: string;
  last: string;
}

/**
 * The measured daily volatility of a real print series: the sample standard deviation of its one-day moves (each print over the previous calendar day's, less one), over
 * every pair of prints on consecutive days. Decimal arithmetic, never floats.
 */
export function dailyVolatility(series: readonly DatedPrint[]): Volatility {
  const sorted = [...series].sort((a, b) => a.date.localeCompare(b.date));
  const moves: { date: string; r: DecimalValue }[] = [];
  for (let i = 1; i < sorted.length; i++) {
    const a = sorted[i - 1] as DatedPrint;
    const b = sorted[i] as DatedPrint;
    const next = new Date(`${a.date}T00:00:00Z`);
    next.setUTCDate(next.getUTCDate() + 1);
    if (next.toISOString().slice(0, 10) !== b.date) continue;
    moves.push({ date: b.date, r: new D(b.datedSiu).div(a.datedSiu).minus(1) });
  }
  if (moves.length < 2) throw new Error("volatility: fewer than two consecutive-day moves");
  const mean = moves.reduce((s, m) => s.plus(m.r), new D(0)).div(moves.length);
  const variance = moves.reduce((s, m) => s.plus(m.r.minus(mean).pow(2)), new D(0)).div(moves.length - 1);
  const max = moves.reduce((m, x) => (x.r.abs().gt(m.r.abs()) ? x : m));
  const ppm = (x: DecimalValue): bigint => BigInt(x.times(1_000_000).toDecimalPlaces(0, D.ROUND_HALF_UP).toFixed(0));
  return {
    pairs: moves.length,
    sdPpm: ppm(variance.sqrt()),
    maxMove: { date: max.date, ppm: ppm(max.r) },
    first: sorted[0]?.date as string,
    last: sorted.at(-1)?.date as string,
  };
}
