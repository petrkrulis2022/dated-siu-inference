// `Env` here is the ambient global from worker-configuration.d.ts (generated by `wrangler
// types` — see env.ts's doc comment), not a locally declared type; `WorkerEnv` adds the
// optional secrets and bindings that file does not describe (./worker-env.ts).

export { TouchstoneMcpAgent };

const app = new Hono<{ Bindings: WorkerEnv }>();

// Enables the free get_index tool to be called live from a browser (both public sites' own
// "Try it here" pages) — before this, every response here carried no CORS headers at all, so a
// cross-origin fetch() from either site's own JS was silently blocked by the browser, even
// though a non-browser caller (curl, this repo's own agents) was never subject to CORS in the
// first place. Purely additive: no payment/business logic changes. Scoped to exactly the two
// real site origins, never a wildcard. exposeHeaders is not optional — the browser-side session
// handshake reads the Mcp-Session-Id response header, and per the Fetch spec a cross-origin
// response only exposes "simple" headers to JS unless Access-Control-Expose-Headers names it.
const ALLOWED_ORIGINS = new Set([
  "https://prints.touchstoneassay.com",
  "https://touchstoneassay.com",
]);
app.use(
  "*",
  cors({
    origin: (origin) => (origin && ALLOWED_ORIGINS.has(origin) ? origin : ""),
    allowMethods: ["POST"],
    exposeHeaders: ["Mcp-Session-Id"],
  }),
);

/**
 * Runs get_quote's or convert's exact own computation ahead of the paywall, so a call that cannot
 * succeed never reaches it — the data-dependent half of "never charge for a failure" (an unknown or
 * excluded model); the input half is ../tools/schemas.ts, run by the paywall itself. Interim for
 * get_quote — see docs/methodology.md's "declared run-record manifest" note: once publish time
 * writes data/runs/<print_id>/index.json, get_quote stops depending on GitHub's Contents API (the
 * actual thing that can fail here). Until then: a buyer paying for a call that errors is the worst
 * first impression this service can give, so this trades one extra (cached) read for never charging
 * for a failure. convert was added 2026-10-24: it fails the same way for a model the print excludes.
 */
async function paidCallWouldSucceed(
  toolName: "get_quote" | "convert",
  args: Record<string, unknown>,
  env: Env,
): Promise<boolean> {
  const t0 = Date.now();
  try {
    const dataSource = githubDataSource(env.PRINTS_CACHE);
    const { print } = await dataSource.loadLatestPrint();
    const snapshot = await dataSource.loadPriceSnapshot(print.price_snapshot_ref);
    if (toolName === "convert") {
      convertTool(args as unknown as ConvertInput, print, snapshot);
    } else {
      const input = args as unknown as GetQuoteInput;
      const allRecords = await dataSource.loadRunRecords(print.print_id);
      const modelRecords = allRecords.filter((r) => r.model_id === input.model);
      getQuoteTool(input, print, snapshot, modelRecords);
    }
    console.log(`[latency] ${toolName} would succeed: ${Date.now() - t0}ms (ok)`);
    return true;
  } catch (err) {
    console.log(
      `[latency] ${toolName} would succeed: ${Date.now() - t0}ms (would fail: ${err instanceof Error ? err.message : String(err)})`,
    );
    return false;
  }
}

/**
 * One route, exactly as the Node/Express deployment has — an MCP client always POSTs every tool
 * call to the same endpoint, so which tool is being called (and therefore whether payment is
 * required) can only be known by inspecting the JSON-RPC body, never the URL. The paywall dispatch
 * (../paywall.ts, unchanged, already tested) runs first via a minimal req/res shim
 * (./node-shim.js) — a real 402 challenge from Circle's real Gateway, not a reimplementation of
 * the x402 protocol. Only once payment clears (or the tool is free — createDispatcher's own
 * bypass, also unchanged) does the request reach the MCP layer, delegated to the McpAgent Durable
 * Object.
 */
app.post("/mcp", async (c) => {
  const bodyText = await c.req.text();
  let body: unknown;
  try {
    body = bodyText ? JSON.parse(bodyText) : undefined;
  } catch {
    body = undefined;
  }
  const toolName = extractToolCallName(body);
  // Which listing brought this call (./channel.ts): the URL's ?via= tag, or, for a session whose
  // client dropped it, the tag remembered when the session began. Read only when a call is recorded.
  const sessionHeader = c.req.header("mcp-session-id");
  const urlChannel = channelFrom(c.req.url);
  const channelFor = async (): Promise<string> =>
    urlChannel !== "direct" || !sessionHeader
      ? urlChannel
      : channelFrom(c.req.url, await sessionChannel(c.env.PRINTS_CACHE, sessionHeader));

  // The request's body was consumed by c.req.text() above and a Request's body stream can be read
  // only once, so every hand-off to the MCP agent rebuilds the request around the buffered text.
  // Hono's ExecutionContext is a narrower structural subset of @cloudflare/workers-types' — both
  // describe the same runtime object; McpAgent.serve()'s .fetch() just wants the fuller shape.
  const forwardToAgent = (): Promise<Response> =>
    TouchstoneMcpAgent.serve("/mcp", { binding: "TOUCHSTONE_MCP" }).fetch(
      new Request(c.req.raw, { body: bodyText }),
      c.env,
      c.executionCtx as unknown as ExecutionContext,
    );

  // A paid call with no MCP session can only be refused by the agent (400: initialize first), and
  // the paywall settles BEFORE the agent runs — found live 2026-10-25: such a call paid on all
  // three networks and then got only an error. Pass it through unpaid; the agent's own refusal is
  // the answer, and the client opens a session and tries again having lost nothing.
  if (
    toolName !== undefined &&
    Object.hasOwn(TOOL_PRICES, toolName) &&
    !c.req.header("mcp-session-id")
  ) {
    return forwardToAgent();
  }

  if (toolName === "get_quote" || toolName === "convert") {
    const args = extractToolCallArguments(body);
    if (
      typeof args === "object" &&
      args !== null &&
      !(await paidCallWouldSucceed(toolName, args as Record<string, unknown>, c.env))
    ) {
      // Skip the paywall entirely — forwarding straight to the MCP agent, unpaid, gives the
      // client the same correctly-formatted isError result the tool would return anyway, for
      // free, instead of collecting a payment first and only then discovering the call fails.
      return forwardToAgent();
    }
  }

  // The network profile for THIS request — a KV flag read every time, with the env default and a
  // testnet fallback (../networks.ts), so switching between mainnet, testnet and the old
  // Base-Sepolia-only behaviour is a KV write, never a deploy (brief decision 5, rollback §12).
  const profile = await resolveProfile(c.env.PRINTS_CACHE, c.env.TOUCHSTONE_NETWORK_PROFILE);
  const profileConfig = PROFILES[profile];

  // A tool this profile cannot honestly deliver is never charged for: answer it here, unpaid, with
  // the reason, as the tool-execution error a client already knows how to show.
  const unavailable = toolName ? profileConfig.unavailableTools[toolName] : undefined;
  if (unavailable) {
    const id = (body as { id?: unknown } | undefined)?.id ?? null;
    return Response.json({
      jsonrpc: "2.0",
      id,
      result: { content: [{ type: "text", text: unavailable }], isError: true },
    });
  }

  const paywall = paywallFor(profile, c.env);
  const { req, res, next, settled, getResult, nextCalled, responseHeaders } = createNodeShim(
    c.req.raw,
    body,
  );
  // paywall(req, res, next) itself returns void synchronously (../paywall.ts's dispatchPaywall
  // calls the real middleware as `void middleware(...)`) — awaiting that resolves before Circle's
  // Gateway verify/settle call has done anything. `settled` is what actually waits for it.
  const tPaywall0 = Date.now();
  paywall(req, res, next);
  await Promise.race([
    settled,
    new Promise<never>((_, reject) =>
      setTimeout(() => reject(new Error("paywall timed out")), 25_000),
    ),
  ]);
  console.log(
    `[latency] paywall dispatch (Circle Gateway round-trip): ${Date.now() - tPaywall0}ms — ${nextCalled() ? "cleared/free" : "402 challenge"}`,
  );

  const sessionId = c.req.header("mcp-session-id");
  if (!nextCalled()) {
    const result = getResult();
    const status = result?.status ?? 402;
    // The SIU-price measures (./siu-measures.ts): every 402, and whether it carried an SIU price.
    if (toolName && status === 402) {
      recordChallenge(c.env, c.executionCtx, toolName, profile, siuPricedFrom(req) ?? false, sessionId, await channelFor());
    }
    return new Response(result?.body ?? "", {
      status,
      headers: { ...result?.headers, "x-touchstone-network-profile": profile },
    });
  }

  // Usage data point for every call and, for a paid one, the settlement-log row (brief decision 4):
  // never able to fail the call — see ./record-call.ts.
  if (toolName) {
    const payment = paymentFrom(req);
    const channel = await channelFor();
    recordCall(
      c.env,
      c.executionCtx,
      toolName,
      payment,
      profileConfig.selfSettled.map((n) => n.network),
      channel,
    );
    if (payment?.network) recordPaidInSession(c.env, c.executionCtx, toolName, profile, sessionId, channel);
  }

  const tMcp0 = Date.now();
  const mcpResponse = await forwardToAgent();
  console.log(`[latency] MCP agent (Durable Object) tool execution: ${Date.now() - tMcp0}ms`);
  // A tagged client opening a session: remember its listing for the session's later requests.
  const newSession = mcpResponse.headers.get("mcp-session-id");
  if (newSession && !sessionHeader && urlChannel !== "direct") {
    c.executionCtx.waitUntil(rememberSessionChannel(c.env.PRINTS_CACHE, newSession, urlChannel));
  }

  // A cleared payment's PAYMENT-RESPONSE header (the settlement receipt) was set on the shim's
  // throwaway res, not on the real response — carry it across, per the x402 protocol's own
  // expectation that a settled call's response includes it.
  const paymentResponseHeader = responseHeaders()["PAYMENT-RESPONSE"];
  // A paying client that asks for JSON gets the single reply as JSON rather than a one-event
  // stream it cannot parse (./json-response.ts); everyone else gets the transport's own reply.
  const reply = await singleReplyAsJson(mcpResponse, c.req.header("accept") ?? null);
  if (paymentResponseHeader) {
    const withHeader = new Response(reply.body, reply);
    withHeader.headers.set("PAYMENT-RESPONSE", paymentResponseHeader);
    return withHeader;
  }
  return reply;
});

// The REST door to the same four tools (/v1/index, /v1/quote, /v1/convert, /v1/verify-receipt) and
// its OpenAPI document (/openapi.json): plain HTTP routes that answer 402 on their own URL, which is
// what an x402 marketplace lists and probes. Same tool glue, same paywall, same settlement log as
// the MCP route above — see ./rest.ts.
app.route(
  "/",
  createRestApp<WorkerEnv>({
    profileFor: (env) => resolveProfile(env.PRINTS_CACHE, env.TOUCHSTONE_NETWORK_PROFILE),
    paywallFor: restPaywallFor,
    toolDepsFor: (env) => ({
      dataSource: githubDataSource(env.PRINTS_CACHE),
      settlementReader: new OnChainSettlementReader({
        chainName: env.TOUCHSTONE_CHAIN_NAME,
        rpcUrl: env.BASE_SEPOLIA_RPC_URL,
        escrowAddress: env.TOUCHSTONE_ESCROW_ADDRESS,
      }),
      attestationPrivateKeyHex: env.TOUCHSTONE_ATTESTATION_KEY,
    }),
    record: recordCall,
    // REST calls carry no session, so their 402s count toward coverage only.
    recordChallenge: (env, ctx, tool, profile, siuPriced, channel) =>
      recordChallenge(env, ctx, tool, profile, siuPriced, undefined, channel),
  }),
);

export default app;
