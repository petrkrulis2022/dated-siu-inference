#!/usr/bin/env node
// Regenerates marketing/src/components/pages/home/content.ts from the latest published print,
// so the marketing site's hero figure can never drift from the real Dated SIU print — this runs
// as a build-command prefix step in the Cloudflare Pages project, so a push after a new print
// publishes automatically regenerates and redeploys the marketing site too.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { URL, fileURLToPath } from "node:url";

const REPO_ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const LATEST_PRINT_FILE = resolve(REPO_ROOT, "data/prints/latest.json");
const CONTENT_FILE = resolve(REPO_ROOT, "marketing/src/components/pages/home/content.ts");
const PUBLICATION_URL = "https://prints.touchstoneassay.com/";

async function main() {
  const print = JSON.parse(await readFile(LATEST_PRINT_FILE, "utf-8"));

  const content = `export const PUBLICATION_URL = ${JSON.stringify(PUBLICATION_URL)};

/**
 * Generated by scripts/sync-marketing-print.mjs from data/prints/latest.json — do not hand-edit.
 * Replace only by publishing a new print; this file is regenerated on every marketing build.
 * Source print: ${print.print_id}.
 */
export const CURRENT_PRINT = {
  value: ${JSON.stringify(print.dated_siu)},
  date: ${JSON.stringify(print.date)},
  status: ${JSON.stringify(print.status.toUpperCase())},
} as const;
`;

  await writeFile(CONTENT_FILE, content, "utf-8");
  console.log(
    `Synced marketing hero to print ${print.print_id} (${print.dated_siu}, ${print.status}).`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
