#!/usr/bin/env node
// Writes the copies of the paid tools' public facts that cannot import @touchstone/print directly,
// from that package's built output (packages/print/dist), so no page can drift from what the server
// accepts:
//
//   - marketing/src/lib/agent-facts.generated.ts   (the marketing site is its own Astro project)
//   - the facts block in docs/listing.md, between the agent-facts markers
//
// The site (site/) and the server import the same facts directly and need nothing from here.
// Usage: node scripts/generate-agent-surfaces.mjs [--check]
//   --check  write nothing; exit 1 if either output is out of date (CI runs this).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const facts = await import(pathToFileURL(join(ROOT, "packages/print/dist/index.js")).href);
const check = process.argv.includes("--check");

const {
  PAID_TOOL_PRICES_USD,
  MAINNET_PAYMENT_NETWORKS,
  PAYMENT_ROUTE,
  MAINNET_UNAVAILABLE_NOTES,
  SIU_PRICE_DOCS_URL,
  SIU_PRICE_MAX_AGE_DAYS,
  paymentNetworksText,
} = facts;

const SIU_PRICE_RULE =
  `Each 402 payment offer also states the price in mSIU at the latest Commodity print, in a touchstone block ` +
  `beside the USDC amount. It follows the daily print and is omitted when that print is more than ` +
  `${SIU_PRICE_MAX_AGE_DAYS} days old.`;

const ts = (value) => JSON.stringify(value, null, 2);

const marketing = `// GENERATED by scripts/generate-agent-surfaces.mjs from @touchstone/print
// (packages/print/src/siu-price.ts and paid-tools.ts). Do not edit by hand: run
// \`pnpm run agent-surfaces\` at the repo root. CI fails if this file is out of date.
// No mSIU figures here: this site is not rebuilt with each day's print, so it states the rule and
// points at the live figure instead of a number that would go stale.

export const PAID_TOOL_PRICES_USD = ${ts(PAID_TOOL_PRICES_USD)} as const;

export const PAYMENT_NETWORKS = ${ts(MAINNET_PAYMENT_NETWORKS)} as const;

export const PAYMENT_ROUTE = ${JSON.stringify(PAYMENT_ROUTE)};

export const PAYMENT_NETWORKS_TEXT = ${JSON.stringify(paymentNetworksText())};

export const MAINNET_UNAVAILABLE_NOTES: Record<string, string> = ${ts(MAINNET_UNAVAILABLE_NOTES)};

export const SIU_PRICE_RULE = ${JSON.stringify(SIU_PRICE_RULE)};

export const SIU_PRICE_DOCS_URL = ${JSON.stringify(SIU_PRICE_DOCS_URL)};
`;

const short = (a) => `${a.slice(0, 6)}…${a.slice(-4)}`;
const prices = Object.entries(PAID_TOOL_PRICES_USD)
  .map(([tool, usd]) => `\`${tool}\` $${usd}`)
  .join(" · ");
const unavailable = Object.entries(MAINNET_UNAVAILABLE_NOTES)
  .map(([tool, note]) => `\`${tool}\`: ${note}`)
  .join(" ");
const START =
  "<!-- agent-facts:start (generated by scripts/generate-agent-surfaces.mjs; do not edit by hand) -->";
const END = "<!-- agent-facts:end -->";
const block = [
  START,
  "",
  "| Fact | Value |",
  "| --- | --- |",
  `| Payment networks | ${MAINNET_PAYMENT_NETWORKS.map((n) => `${n.name} \`${n.caip2}\` (${n.asset} \`${short(n.assetAddress)}\`)`).join(", ")}: mainnet |`,
  `| Payment route | ${PAYMENT_ROUTE} |`,
  `| Prices (USDC) | \`get_index\` free · ${prices} |`,
  `| Not on mainnet yet | ${unavailable} |`,
  `| SIU price | ${SIU_PRICE_RULE} [How it is computed](${SIU_PRICE_DOCS_URL}). |`,
  "",
  END,
].join("\n");

const outputs = [];

const marketingPath = join(ROOT, "marketing/src/lib/agent-facts.generated.ts");
outputs.push([marketingPath, marketing]);

const listingPath = join(ROOT, "docs/listing.md");
const listing = readFileSync(listingPath, "utf-8");
const startAt = listing.indexOf("<!-- agent-facts:start");
const endAt = listing.indexOf(END);
if (startAt < 0 || endAt < startAt) throw new Error("docs/listing.md has no agent-facts markers");
outputs.push([listingPath, listing.slice(0, startAt) + block + listing.slice(endAt + END.length)]);

let stale = 0;
for (const [path, content] of outputs) {
  let current = "";
  try {
    current = readFileSync(path, "utf-8");
  } catch {
    // missing counts as stale
  }
  if (current === content) continue;
  stale++;
  if (check)
    console.error(`out of date: ${path.slice(ROOT.length + 1)} (run: pnpm run agent-surfaces)`);
  else writeFileSync(path, content);
}
if (check && stale > 0) process.exit(1);
console.log(
  check ? "agent surfaces are up to date." : `agent surfaces written (${stale} changed).`,
);
